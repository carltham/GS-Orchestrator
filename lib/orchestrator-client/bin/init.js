#!/usr/bin/env node

/**
 * GS-Orchestrator Client Generator
 * Inspects target project structure and dynamically generates a custom startupHandler.js
 */

const fs = require('fs');
const path = require('path');

function generateStartupHandler(targetDir) {
  console.log(`🔍 Inspecting project at ${targetDir}...`);

  const hasServerTs = fs.existsSync(path.join(targetDir, 'src', 'server.ts'));
  const hasServerJs = fs.existsSync(path.join(targetDir, 'src', 'server.js')) || fs.existsSync(path.join(targetDir, 'dist', 'server.js'));
  const hasOrchestratorServer = fs.existsSync(path.join(targetDir, 'GS-Orchestrator', 'src', 'server.ts'));
  const hasAngular = fs.existsSync(path.join(targetDir, 'angular.json'));
  const hasVite = fs.existsSync(path.join(targetDir, 'vite.config.ts')) || fs.existsSync(path.join(targetDir, 'vite.config.js'));
  const hasDocker = fs.existsSync(path.join(targetDir, 'docker-compose.yml')) || fs.existsSync(path.join(targetDir, 'docker-compose.yaml'));

  let pkgName = path.basename(targetDir);
  const pkgPath = path.join(targetDir, 'package.json');
  if (fs.existsSync(pkgPath)) {
    try {
      const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
      if (pkg.name) pkgName = pkg.name;
    } catch (e) {
      // ignore
    }
  }

  const codeBlocks = [];

  // 1. GS-Orchestrator Self Check
  if (hasOrchestratorServer) {
    codeBlocks.push(`
  // GS-Orchestrator Server
  const orchestratorPath = path.join(__dirname, 'GS-Orchestrator', 'src', 'server.ts');
  console.log('⏳ Starting GS-Orchestrator server on port 9000...');
  const orchestratorProc = spawn('npx', ['--yes', 'ts-node', orchestratorPath], {
    cwd: path.dirname(orchestratorPath),
    stdio: 'inherit',
    shell: true,
    detached: true,
  });
  orchestratorProc.unref();
  console.log('✅ GS-Orchestrator server spawned.');`);
  } else if (hasServerTs) {
    codeBlocks.push(`
  // Backend Service (TypeScript)
  const backendPath = path.join(__dirname, 'src', 'server.ts');
  console.log('⏳ Starting Backend service (ts-node)...');
  const backendProc = spawn('npx', ['--yes', 'ts-node', backendPath], {
    cwd: path.dirname(backendPath),
    stdio: 'inherit',
    shell: true,
    detached: true,
  });
  backendProc.unref();
  console.log('✅ Backend process spawned.');`);
  } else if (hasServerJs) {
    const jsPath = fs.existsSync(path.join(targetDir, 'dist', 'server.js')) ? "path.join(__dirname, 'dist', 'server.js')" : "path.join(__dirname, 'src', 'server.js')";
    codeBlocks.push(`
  // Backend Service (JavaScript)
  const backendPath = ${jsPath};
  console.log('⏳ Starting Backend service (node)...');
  const backendProc = spawn('node', [backendPath], {
    cwd: path.dirname(backendPath),
    stdio: 'inherit',
    shell: true,
    detached: true,
  });
  backendProc.unref();
  console.log('✅ Backend process spawned.');`);
  }

  // 2. Frontend Check
  if (hasAngular) {
    codeBlocks.push(`
  // Frontend Service (Angular)
  console.log('⏳ Starting Angular frontend (ng serve)...');
  const frontendProc = spawn('npx', ['ng', 'serve'], {
    cwd: __dirname,
    stdio: 'inherit',
    shell: true,
    detached: true,
  });
  frontendProc.unref();
  console.log('✅ Angular frontend process spawned.');`);
  } else if (hasVite) {
    codeBlocks.push(`
  // Frontend Service (Vite)
  console.log('⏳ Starting Vite frontend...');
  const frontendProc = spawn('npx', ['vite'], {
    cwd: __dirname,
    stdio: 'inherit',
    shell: true,
    detached: true,
  });
  frontendProc.unref();
  console.log('✅ Vite frontend process spawned.');`);
  }

  // 3. Database Check
  if (hasDocker) {
    codeBlocks.push(`
  // Database Service (Docker Compose)
  console.log('⏳ Starting Database container (docker compose up)...');
  const dbProc = spawn('docker', ['compose', 'up', '-d', 'postgres'], {
    cwd: __dirname,
    stdio: 'inherit',
    shell: true,
    detached: true,
  });
  dbProc.unref();
  console.log('✅ Database container command executed.');`);
  }

  if (codeBlocks.length === 0) {
    codeBlocks.push(`
  console.warn('⚠️ No default components detected for ${pkgName}. Edit startupHandler.js to specify start commands.');`);
  }

  const handlerContent = `const { spawn } = require('child_process');
const path = require('path');
const fs = require('fs');

/**
 * Auto-generated Startup Handler for ${pkgName}
 * Generated by @gs/orchestrator-client
 */
function main() {
  console.log('🚀 [startupHandler] Starting services for ${pkgName}...');
${codeBlocks.join('\n')}
}

main();
`;

  const outputPath = path.join(targetDir, 'startupHandler.js');
  fs.writeFileSync(outputPath, handlerContent, 'utf-8');
  console.log(`✅ Generated tailored startupHandler.js at ${outputPath}`);

  // Update target package.json
  if (fs.existsSync(pkgPath)) {
    try {
      const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
      pkg.scripts = pkg.scripts || {};
      pkg.scripts['startupHandler'] = 'node startupHandler.js';
      fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2), 'utf-8');
      console.log(`✅ Added "startupHandler" script to ${pkgPath}`);
    } catch (e) {
      console.error('Failed to update package.json:', e);
    }
  }
}

// Execute when run directly as CLI
if (require.main === module) {
  const targetDir = process.cwd();
  generateStartupHandler(targetDir);
}

module.exports = { generateStartupHandler };
